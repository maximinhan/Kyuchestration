package com.kyuchestration.desktop.terminal

/**
 * 세션 하나를 열 때 그 세션이 쓸 대화를 어느 쪽으로 정할지.
 *
 * **앱은 대화 ID 를 들고 있지 않다.** 고르는 것은 갈래 둘뿐이고, 어느 ID 를 이어갈지도 새 ID 를
 * 무엇으로 할지도 엔진이 정한다(설계 원칙 11 · 설계 문서 5.5.3). 앱이 ID 를 쥐면 기록 파일의
 * 자리와 모양을 두 곳이 알게 되고, 그 앎은 조용히 갈라진다.
 *
 * 참·거짓 하나로 두지 않는다. `enterSession(path, target, true)` 를 읽는 사람은 그 참이
 * 이어가기인지 새로 시작인지 알 수 없고, 두 갈래는 한쪽이 되돌릴 수 없는 일이다.
 */
enum class SessionConversationChoice {

    /**
     * 적혀 있는 대화가 있으면 이어간다. 없으면 새 대화가 열린다.
     *
     * 카드를 그냥 누른 자리이고, 이것이 기본이다 — 사용자가 아무것도 고르지 않으면 대화가 이어진다.
     */
    ContinueRecordedConversation,

    /**
     * 적혀 있는 대화를 버리고 새로 시작한다.
     *
     * **되돌릴 수 없다.** 앞 대화를 가리키던 기록이 그 자리에서 새 것으로 바뀐다. 그래서 화면은
     * 이 길을 사용자가 일부러 고른 자리에만 낸다 — 이어갈 대화가 있는 카드의 버튼과, 이어가지
     * 못한 채 끝난 세션의 머리말.
     */
    StartNewConversation,
}
